def get_tr(key, lang='EN'):
    """Get translation for a key"""
    if lang == 'RU':
        return RU.get(key, key)
    elif lang == 'BOTH':
        en_val = EN.get(key, key)
        ru_val = RU.get(key, key)
        if en_val == ru_val:
            return en_val
        return f"{en_val} / {ru_val}"
    return EN.get(key, key)