BOTH = {}
for key in EN:
    if key == 'lang_toggle':
        BOTH[key] = '🌐 EN+RU'
    else:
        BOTH[key] = f"{EN[key]} / {RU[key]}"


def get_tr(lang):
    """Returns a translation function for the given language mode."""
    if lang == 'RU':
        d = RU
    elif lang == 'BOTH':
        d = BOTH
    else:
        d = EN

    def tr(key):
        return d.get(key, EN.get(key, key))

    return tr